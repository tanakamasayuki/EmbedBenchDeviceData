#!/usr/bin/env python3
"""Write a chip's register table from knowledge/<chip>.yaml as EmbedBench's
RegTableSpec (devices/src/regtable_model.h): the starting point of a model,
with power-on contents, widths and which registers accept writes. What the
table cannot say (timing, side effects) stays in the knowledge file for the
hand-written hooks.

    python3 tools/knowledge_table.py qmp6988 > qmp6988_table.h
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent


def ident(chip: str) -> str:
    return "".join(part.capitalize() for part in chip.replace("_", "-").split("-"))


def render(chip: str) -> str:
    data = yaml.safe_load((REPO_ROOT / "knowledge" / f"{chip}.yaml").read_text(encoding="utf-8"))
    name = ident(chip)
    lines = [f"// Generated by EmbedBenchDeviceData tools/knowledge_table.py from",
             f"// knowledge/{chip}.yaml. Regenerate rather than edit.",
             "#pragma once", "", "#include <regtable_model.h>", ""]
    entries = []
    for reg in data["registers"]:
        addr = int(reg["addr"], 16)
        value = bytes.fromhex(reg["reset"])
        if len(value) != reg["width"]:
            raise SystemExit(f"{reg['addr']}: reset is {len(value)} bytes, width {reg['width']}")
        array = f"k{name}Reset_{addr:02X}"
        lines.append(f"// {reg['addr']} {reg.get('name', '')}: {reg['width']} byte(s), {reg['access']}"
                     + (", per specimen" if reg.get("per_specimen") else ""))
        lines.append(f"static const uint8_t {array}[{reg['width']}] = {{"
                     + ", ".join(f"0x{b:02X}" for b in value) + "};")
        flags = []
        if "w" in reg["access"]:
            flags.append("RegTableModel::kWritable")
        if reg.get("volatile"):
            flags.append("RegTableModel::kVolatile")
        entries.append(f"    {{0x{addr:02X}, {reg['width']}, {array}, {' | '.join(flags) or '0'}}},")
    count = len(entries)
    rs = "true" if data.get("addressing", {}).get("repeated_start_required") else "false"
    lines += ["", f"static const RegTableEntry k{name}Entries[{count}] = {{", *entries, "};",
              f"static const RegTableSpec k{name}Spec = {{k{name}Entries, {count}, nullptr, 0, {rs}}};"]
    if data.get("addressing", {}).get("read_auto_increment"):
        lines += ["", "// Reads auto-increment across registers: the table answers at most one",
                  "// register's width, so a model needs an onRead hook for longer reads."]
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    sys.stdout.write(render(sys.argv[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
